#!/usr/bin/env bash
# Build the state a dispatcher sees when S1/main reports done: main, the story
# branch, and the track branch in its own worktree with the agent's commits.
# The agent stayed in its files except for backend/uv.lock, which S1 does not own.
set -eu
# It runs `git init` and commits in the current directory, so it must only run
# in the eval's scratch copy of the case files, never inside an existing repo.
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "setup-git.sh: $(pwd) is already inside a git repository; run it in an empty scratch copy" >&2
  exit 1
fi
repo=$(pwd)
git init -q -b main
git -c user.email=t@t -c user.name=t add -A
git -c user.email=t@t -c user.name=t commit -qm "initial"
git branch feat/41-render-pdf
trees="$(dirname "$repo")/$(basename "$repo")-tracks"
git worktree add -q -b feat/41-render-pdf--main "$trees/S1-main" feat/41-render-pdf
cd "$trees/S1-main"
cat > backend/app/reports/pdf.py <<'PY'
"""Render a report as a PDF (contract C1)."""

from app.reports.service import Report


def render_pdf(report: Report) -> bytes:
    body = f"BT /F1 12 Tf 72 720 Td ({report.title}) Tj ET"
    return b"%PDF-1.4\n" + body.encode() + b"\n%%EOF\n"
PY
cat > backend/tests/test_pdf.py <<'PY'
from app.reports.pdf import render_pdf
from app.reports.service import get_report


def test_pdf_has_header_and_title():
    out = render_pdf(get_report(1))
    assert out.startswith(b"%PDF")
    assert b"Report 1" in out
PY
sed -i.bak 's/dependencies = \["fastapi>=0.115", "sqlalchemy>=2"\]/dependencies = ["fastapi>=0.115", "sqlalchemy>=2", "reportlab>=4"]/' backend/pyproject.toml && rm backend/pyproject.toml.bak
printf 'version = 1\nrequires-python = ">=3.12"\n# generated by uv\n' > backend/uv.lock
git add -A
git -c user.email=agent@t -c user.name=agent commit -qm "feat(reports): render_pdf for contract C1"
