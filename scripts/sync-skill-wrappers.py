#!/usr/bin/env python3
"""Generate the Claude Code pointers for the skills in `.agents/skills/`.

Each skill lives once, at `.agents/skills/<name>/SKILL.md` (frontmatter + body +
any scripts or references beside it). OpenCode reads `.agents/skills/` natively;
Claude Code only reads `.claude/skills/`, so each skill gets a generated
pointer there whose frontmatter is copied from the canonical file and whose body
says to load it. Nothing else is duplicated, and no `.opencode/skills/` copy is
needed.

Usage:
  python3 scripts/sync-skill-wrappers.py           # write the pointers
  python3 scripts/sync-skill-wrappers.py --check   # exit 1 if any is stale or missing

The same layout is used in rendered projects (`templates/scripts/render.py`
imports `pointer()` from here) so the two cannot drift.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
MARKER = "<!-- generated by scripts/sync-skill-wrappers.py from {src}; do not edit -->"


def pointer(skill_md: str, rel_src: str) -> str:
    """The `.claude/skills/<name>/SKILL.md` text for a canonical skill."""
    m = FRONTMATTER.match(skill_md)
    if not m:
        raise ValueError(f"{rel_src}: missing frontmatter")
    return (
        f"---\n{m.group(1)}\n---\n\n"
        f"{MARKER.format(src=rel_src)}\n\n"
        f"Read and follow the complete instructions at `{rel_src}`.\n\n"
        "Apply the workflow to the following material:\n\n$ARGUMENTS\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate .claude/skills pointers from .agents/skills.")
    ap.add_argument("--check", action="store_true", help="report stale or missing pointers; write nothing")
    args = ap.parse_args()
    stale = []
    for src in sorted((ROOT / ".agents" / "skills").glob("*/SKILL.md")):
        name = src.parent.name
        rel = src.relative_to(ROOT).as_posix()
        want = pointer(src.read_text(encoding="utf-8"), rel)
        dst = ROOT / ".claude" / "skills" / name / "SKILL.md"
        have = dst.read_text(encoding="utf-8") if dst.is_file() else None
        if have == want:
            continue
        stale.append(dst.relative_to(ROOT).as_posix())
        if not args.check:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(want, encoding="utf-8")
    if args.check and stale:
        for s in stale:
            print(f"STALE: {s} (run python3 scripts/sync-skill-wrappers.py)", file=sys.stderr)
        return 1
    verb = "would update" if args.check else "updated"
    print(f"skill pointers: {len(stale)} {verb}" if stale else "skill pointers: up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
